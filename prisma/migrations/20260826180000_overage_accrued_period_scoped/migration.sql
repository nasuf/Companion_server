-- 对话超额小数账本按额度周期隔离，不再无限期跨天/跨月累积。
--
-- overage_accrued 之前是纯全局字段：只要账上残留过任何 < 1 的历史欠账（哪怕
-- 是很久以前某次超额发送遗留的 0.5），下一次超额确认发送都会把"历史残留 +
-- 本次 per_msg_cost"一起结算——一旦凑够 1 就立刻整数扣款，且扣的是用户"当前"
-- 的钞票余额，跟这是不是本次对话/本周期第一次超额完全无关。用户报告"剩余 1
-- 钞票、确认发送第一句后第二句就被拒"正是这个机制：历史遗留的 0.5 和这次的
-- 0.5 一起凑成 1，把仅有的 1 钞票直接扣光。
--
-- 加 overage_period 记录"当前 overage_accrued 累积所属的周期"(格式
-- "{period_scope}:{period_key}", 如 "day:2026-08-26" / "month:2026-08")。
-- chat_quota.consume_one 读取时若发现存的周期跟当前不一致, 就把上个周期
-- 没凑够 1 的欠账视为放弃(不再收), 从 0 开始重新累积——跟免费额度本身
-- "新周期从头开始"的心智模型保持一致。
ALTER TABLE user_wallets
    ADD COLUMN IF NOT EXISTS overage_period TEXT;
