"""给 (用户消息, 召回记忆) 配对判"这条记忆对回复有没有用".

判的不是"两段文本像不像" —— 那正是向量相似度已经在做的事, 再问一遍等于同义反复.
判的是**注入这条记忆会不会让回复更贴这个人**: 换个用户说同一句话, 这条记忆还成立
就说明它没提供任何个人化信息, 属于噪声.

评审模型给的是三档而不是二值, 因为 0.5-0.65 那一带大量配对是"沾边但用不上"
(用户说"晚上吃会胖", 记忆是"晚上约朋友吃东南亚菜"), 硬压成有用/无用会把阈值
标定的结论推向标注者的主观倾向.
"""

from __future__ import annotations

JUDGE_PROMPT = """你在评估一个 AI 伴侣的长期记忆检索质量。

用户刚说了这句话：
{message}

系统召回了这条记忆，它属于**{owner}**：
{memory}

判断：**在生成回复时把这条记忆放进上下文，对这一轮回复有用吗？**

判定标准（重要）：
- 有用 = 这条记忆讲的正是这句话涉及的那个人/那件事/那个偏好，引用它能让回复
  明显更具体。分两种情况：
  · 用户的记忆 —— 让 AI 记得这个用户是谁、聊过什么、有什么偏好。检验方法：换成
    另一个陌生用户说同样这句话，这条记忆就用不上了，那它就是有价值的个人化信息。
  · AI 自己的记忆 —— 让 AI 回答关于自己的问题时保持人设一致。用户问"你喜欢
    什么/你去过吗/你怎么看"时，AI 自己的相关偏好、经历、观点就是有用的，
    **不要因为它不是用户的信息就判无用**。
- 沾边 = 话题上有关联，但引用它并不能让回复更准确，甚至会让 AI 说出牵强的联想。
  典型是同一个大类别下的不同具体事物（问"晚上吃会胖"召回"晚上约朋友吃饭"）。
- 无用 = 完全不相干，或者内容太泛以至于对任何一句话都"沾边"。

注意：不要因为两段文字有相同的词就判有用。词面重合是检索算法已经做过的事，你要
判的是语义上能不能真的用上。

只输出一个词：有用 / 沾边 / 无用"""


def parse_verdict(raw: str) -> str | None:
    text = (raw or "").strip()
    # 顺序要紧: "无用" 与 "有用" 都含 "用", 先判否定
    for label in ("无用", "沾边", "有用"):
        if label in text:
            return label
    return None
