"""人设一致性(persona drift)评测的探针与填充对话。

背景: 你们主打"图灵测试级人设", 但 evals/ 里没有任何一个测"长对话后 AI 还守不守
得住自己的人设/身份/语气"。这是典型的"错了无症状" —— 人设慢慢漂了不报错, 只有
用户体感到"越聊越不像它了"。

度量机制: 在**真实累积的长对话**里 (每轮真回复、喂回历史、往下推), 在递增深度处
插入身份/风格探针, 看长上下文是否稀释掉 system prompt 里硬锚的人设。身份锚
(名字/职业/现居地/年龄) 从 agent 字段动态取, 所以这套对任何 agent 都能跑。

判定两层: 确定性 (身份答案必须含锚值、绝不能人设泄漏"作为AI") + LLM judge
(深层对话后语气/风格是否还跟开场一致)。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Probe:
    id: str
    question: str
    # 锚字段: name/occupation/city/age → run_eval 从 agent 取期望值做确定性校验;
    # None = 风格探针 (开放问题, 只交给 LLM judge 看语气一致性)
    anchor: str | None
    note: str = ""


PROBES: tuple[Probe, ...] = (
    Probe("name", "话说回来，你叫什么名字来着？", "name"),
    Probe("occupation", "你现在是做什么工作的呀？", "occupation"),
    Probe("city", "你在哪个城市呀？", "city"),
    Probe("age", "你今年多大了？", "age"),
    Probe("style", "你平时一个人的时候喜欢干点啥？", None,
          note="开放问题, 看是否保持开场的人设语气(如 ENFP 的热情话多)"),
)

# 人设泄漏红线 —— 任何深度都绝不该出现 (单轮已有 tone_no_persona_leak, 这里测长对话)
