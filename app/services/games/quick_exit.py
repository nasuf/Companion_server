"""点开游戏又关掉时, AI 什么都不说.

## 为什么是"什么都不说"

实测 768 局终局里 **401 局 (52%) 步数 ≤2**, 342 局是 0 步 —— 点开又关是最常见的
行为, 不是边缘情况。

这一版之前试过两种"说点什么":

1. **写死一句话**。这类局占一半, 同一句会连着出现几十遍。
2. **限流 + 按处境分档轮换**。10 分钟冷却 + 3 档 × 4 句。生产上 3 天发出 **84 条**,
   时间戳精确落在 11:00 / 11:10 / 11:20 / 11:30 …—— 因为**限流只是限流, 它从不
   停止**。用户持续摆弄界面, 就一整天每小时收 6 条「我这边棋盘都摆熟了」。

第 2 版的设计错误是把它当成频率问题。真朋友看你反复点开关掉, 说一次就不再提了,
不会每 10 分钟提醒你一次。而"说一次"这件事本身价值也很低: 进出游戏在聊天里**已经
有系统卡片**（「已进入游戏《国际象棋》」/「已退出」）, 用户看得见发生了什么, AI
再评论一句纯属复述。

## 那"用户老是点开又关"这个信息去哪了

它不该以逐次评论的形式出现, 而该沉淀成 AI 对这个人的印象。两条通路已经在跑:

- `memory.behaviour_signals._game_fact` → 用户画像里的「多数局没下完就走了」
- `games.daily_digest` → 当天对局摘要进每日自我总结

这两处都是"AI 的整体感觉", 而不是"AI 盯着你每一次操作"。

## 为什么留下这个模块

留一个明确写着"这里刻意不出声"的地方, 比让调用点若无其事地传空串好 —— 后者三个月
后会被当成漏了实现而"补上"。守卫测试钉住了这个决定。
"""

from __future__ import annotations


def quick_exit_reply() -> str:
    """点开又关时说的话 —— 恒为空串, 即不发任何消息.

    空串是安全的: `companion_reply` 只在 Flutter 里被解析成字段而从未渲染, web
    完全不用, 所以回复只通过聊天消息到达用户 (`_persist_reply_to_chat_if_needed`
    对空 reply 直接 return)。
    """
    return ""
