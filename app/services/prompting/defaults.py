# 工程补丁: AI 自洽性约束. spec §4 日常交流的"汇总参考信息" 不含 AI 当前作息,
# 我们之前为此把 schedule_context 从 §4 主回复 prompt 移除. 但极端场景下
# (≥1min 延迟 + 单意图日常交流) 主回复 LLM 既没 schedule 段也没"回复时机说明"
# (后者 spec §6.5 规定 ≥1min 时由独立"延迟解释回复"承担), LLM 可能编造
# 跟实际状态矛盾的活动 (e.g. "刚去爬山" 但 AI 实际在睡眠).
# 这段以"约束"框架注入: 告诉 LLM 自己当前在做什么, 但明确禁止主动展开,
# 避免 §3.4.3 询问当前状态的输出主题被同质化 (那是 §3.4.3 专属的工作).
# 占位符: {activity} (e.g. "看剧/看书"), {status} (e.g. "idle"/"busy"/"sleep").
